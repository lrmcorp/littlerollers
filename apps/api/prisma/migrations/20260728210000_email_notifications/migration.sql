CREATE TABLE `NotificationOccurrence` (
  `id` CHAR(36) NOT NULL,
  `occurrenceKey` VARCHAR(191) NOT NULL,
  `sourceEventId` CHAR(36) NULL,
  `userId` CHAR(36) NULL,
  `branchId` CHAR(36) NULL,
  `channel` ENUM('EMAIL') NOT NULL DEFAULT 'EMAIL',
  `eventType` VARCHAR(191) NOT NULL,
  `templateKey` VARCHAR(191) NOT NULL,
  `templateVersion` INTEGER NOT NULL DEFAULT 1,
  `recipientHash` VARCHAR(191) NOT NULL,
  `recipientMasked` VARCHAR(191) NOT NULL,
  `envelopeEncrypted` LONGTEXT NULL,
  `status` ENUM('PENDING', 'SENDING', 'ACCEPTED_BY_SMTP', 'FAILED_RETRYABLE', 'FAILED_TERMINAL', 'EXPIRED', 'FALLBACK_IN_APP') NOT NULL DEFAULT 'PENDING',
  `attemptCount` INTEGER NOT NULL DEFAULT 0,
  `rateLimitWaitCount` INTEGER NOT NULL DEFAULT 0,
  `maxAttempts` INTEGER NOT NULL DEFAULT 5,
  `nextAttemptAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `leaseExpiresAt` DATETIME(3) NULL,
  `lastErrorCode` VARCHAR(191) NULL,
  `correlationId` VARCHAR(191) NOT NULL,
  `expiresAt` DATETIME(3) NULL,
  `acceptedAt` DATETIME(3) NULL,
  `fallbackCreatedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `NotificationOccurrence_occurrenceKey_key` (`occurrenceKey`),
  INDEX `NotificationOccurrence_status_nextAttemptAt_idx` (`status`, `nextAttemptAt`),
  INDEX `NotificationOccurrence_userId_createdAt_idx` (`userId`, `createdAt`),
  INDEX `NotificationOccurrence_sourceEventId_idx` (`sourceEventId`),
  INDEX `NotificationOccurrence_branchId_createdAt_idx` (`branchId`, `createdAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `NotificationOccurrence_sourceEventId_fkey` FOREIGN KEY (`sourceEventId`) REFERENCES `OutboxEvent`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `NotificationOccurrence_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `NotificationAttempt` (
  `id` CHAR(36) NOT NULL,
  `occurrenceId` CHAR(36) NOT NULL,
  `attemptNumber` INTEGER NOT NULL,
  `status` ENUM('PENDING', 'SENDING', 'ACCEPTED_BY_SMTP', 'FAILED_RETRYABLE', 'FAILED_TERMINAL', 'EXPIRED', 'FALLBACK_IN_APP') NOT NULL,
  `providerCode` VARCHAR(191) NULL,
  `errorCode` VARCHAR(191) NULL,
  `startedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `completedAt` DATETIME(3) NULL,
  UNIQUE INDEX `NotificationAttempt_occurrenceId_attemptNumber_key` (`occurrenceId`, `attemptNumber`),
  INDEX `NotificationAttempt_status_startedAt_idx` (`status`, `startedAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `NotificationAttempt_occurrenceId_fkey` FOREIGN KEY (`occurrenceId`) REFERENCES `NotificationOccurrence`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
