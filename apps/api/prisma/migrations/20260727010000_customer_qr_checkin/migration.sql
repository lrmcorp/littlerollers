CREATE TABLE `CheckInToken` (
  `id` CHAR(36) NOT NULL,
  `bookingId` CHAR(36) NOT NULL,
  `issuedById` CHAR(36) NOT NULL,
  `tokenHash` VARCHAR(191) NOT NULL,
  `activeBookingKey` CHAR(36) NULL,
  `idempotencyKeyHash` VARCHAR(191) NOT NULL,
  `requestHash` VARCHAR(191) NOT NULL,
  `purpose` VARCHAR(191) NOT NULL DEFAULT 'CUSTOMER_CHECK_IN',
  `notBeforeAt` DATETIME(3) NOT NULL,
  `expiresAt` DATETIME(3) NOT NULL,
  `status` ENUM('ACTIVE', 'USED', 'REVOKED') NOT NULL DEFAULT 'ACTIVE',
  `usedAt` DATETIME(3) NULL,
  `revokedAt` DATETIME(3) NULL,
  `version` INTEGER NOT NULL DEFAULT 0,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `CheckInToken_tokenHash_key` (`tokenHash`),
  UNIQUE INDEX `CheckInToken_activeBookingKey_key` (`activeBookingKey`),
  UNIQUE INDEX `CheckInToken_issuedById_idempotencyKeyHash_key` (`issuedById`, `idempotencyKeyHash`),
  INDEX `CheckInToken_bookingId_status_expiresAt_idx` (`bookingId`, `status`, `expiresAt`),
  INDEX `CheckInToken_expiresAt_status_idx` (`expiresAt`, `status`),
  CONSTRAINT `CheckInToken_bookingId_fkey` FOREIGN KEY (`bookingId`) REFERENCES `Booking`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `CheckInToken_issuedById_fkey` FOREIGN KEY (`issuedById`) REFERENCES `User`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

