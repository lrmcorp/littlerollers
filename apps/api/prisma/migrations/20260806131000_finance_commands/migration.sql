CREATE TABLE `OtherCost` (
  `id` CHAR(36) NOT NULL,
  `branchId` CHAR(36) NOT NULL,
  `period` CHAR(7) NOT NULL,
  `description` VARCHAR(300) NOT NULL,
  `amountRp` INTEGER NOT NULL,
  `evidenceUploadId` CHAR(36) NULL,
  `status` ENUM('ACTIVE', 'REVERSED') NOT NULL DEFAULT 'ACTIVE',
  `createdById` CHAR(36) NOT NULL,
  `version` INTEGER NOT NULL DEFAULT 0,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  INDEX `OtherCost_branchId_period_createdAt_id_idx`(`branchId`, `period`, `createdAt`, `id`),
  INDEX `OtherCost_status_period_idx`(`status`, `period`),
  PRIMARY KEY (`id`),
  CONSTRAINT `OtherCost_branchId_fkey` FOREIGN KEY (`branchId`) REFERENCES `Branch`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `OtherCost_createdById_fkey` FOREIGN KEY (`createdById`) REFERENCES `User`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `FinancePeriod` (
  `id` CHAR(36) NOT NULL,
  `branchId` CHAR(36) NOT NULL,
  `period` CHAR(7) NOT NULL,
  `status` ENUM('OPEN', 'CLOSING', 'CLOSED') NOT NULL DEFAULT 'OPEN',
  `controlHash` CHAR(64) NOT NULL,
  `closedAt` DATETIME(3) NULL,
  `closedById` CHAR(36) NULL,
  `version` INTEGER NOT NULL DEFAULT 0,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `FinancePeriod_branchId_period_key`(`branchId`, `period`),
  INDEX `FinancePeriod_status_period_idx`(`status`, `period`),
  PRIMARY KEY (`id`),
  CONSTRAINT `FinancePeriod_branchId_fkey` FOREIGN KEY (`branchId`) REFERENCES `Branch`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `FinancePeriod_closedById_fkey` FOREIGN KEY (`closedById`) REFERENCES `User`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `FinanceCorrection` (
  `id` CHAR(36) NOT NULL,
  `branchId` CHAR(36) NOT NULL,
  `currentPeriod` CHAR(7) NOT NULL,
  `referencePeriod` CHAR(7) NOT NULL,
  `amountRp` INTEGER NOT NULL,
  `reason` VARCHAR(500) NOT NULL,
  `requestedById` CHAR(36) NOT NULL,
  `decidedById` CHAR(36) NULL,
  `decisionReason` VARCHAR(500) NULL,
  `status` ENUM('PENDING', 'APPROVED', 'POSTED', 'REJECTED') NOT NULL DEFAULT 'PENDING',
  `decidedAt` DATETIME(3) NULL,
  `postedAt` DATETIME(3) NULL,
  `version` INTEGER NOT NULL DEFAULT 0,
